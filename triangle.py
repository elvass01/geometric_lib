def area(a, h):
    """
    Принимает длину основания (a) и высоту (h) треугольника, возвращает его площадь

    Пример вызова:

    >>> area(5, 3.2)
    8.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """
    Принимает длины сторон треугольника a, b и c - возвращает его периметр

    Пример вызова:

    >>> perimeter(5, 3.2, 3)
    11.2
    """
    return a + b + c