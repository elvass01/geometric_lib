def area(a, b):
    """
    Принимает стороны прямоугольника a и b - возвращает его площадь

    Пример вызова:

    >>> area(6, 10)
    60
    """
    return a * b

def perimeter(a, b):
    """
    Принимает стороны прямоугольника a и b - возвращает его периметр

    Пример вызова:

    >>> perimeter(2, 10)
    24
    """
    return 2 * (a + b)